import assert from 'node:assert/strict';
import { localVendorCreditEvidence } from './src/vendor-credit-evidence.js';
import { localApAgingEvidenceRows } from './src/aging-local-evidence.js';

const bill={bill_id:7,bill_no:'BILL-7',entity_id:2,vendor_id:9,vendor_name:'Concrete Co',status:'APPROVED',amount:1000,due_date:'2026-07-01',account_code:'164100',je_number:'BILL-JE'};
const ap={je_number:'BILL-JE',posting_status:'POSTED',entity_id:2,lines:[{account_code:'164100',credit_amount:0,debit_amount:1000},{account_code:'291001',credit_amount:1000,debit_amount:0}]};
const credit={je_number:'VCR-7',source_system:'AP_CREDIT',posting_status:'POSTED',entity_id:2,je_date:'2026-07-20',payee:'Concrete Co',source_bill_no:'BILL-7',applied_amount:200,lines:[{account_code:'291001',debit_amount:200,credit_amount:0}]};
const credits=localVendorCreditEvidence({bills:[bill],journals:[credit]});
const row=localApAgingEvidenceRows([bill],[ap,credit],[],'2026-07-31',credits).at(0);
assert.equal(row.applied_credit_amount,200);
assert.equal(row.outstanding_amount,800);
assert.equal(row.aging_state,'VALID_OPEN_POSTED_AP_CREDIT_APPLIED');
const payment={je_number:'PAY-7',posting_status:'POSTED',entity_id:2,payee:'Concrete Co',je_date:'2026-07-15',lines:[{account_code:'291001',debit_amount:750,credit_amount:0},{account_code:'111000',debit_amount:0,credit_amount:750}]};
const paidBill={...bill,pay_je_number:'PAY-7'};
const overCredit={...credit,applied_amount:300};
assert.equal(localVendorCreditEvidence({bills:[paidBill],journals:[payment,overCredit]}).at(0).state,'CREDIT_REVIEW_APPLICATION_LIMIT');
const paymentCredit={...credit,applied_amount:200};
const paidCredits=localVendorCreditEvidence({bills:[paidBill],journals:[payment,paymentCredit]});
const paidRow=localApAgingEvidenceRows([paidBill],[ap,payment,paymentCredit],[],'2026-07-31',paidCredits).at(0);
assert.equal(paidRow.paid_amount,750);
assert.equal(paidRow.applied_credit_amount,200);
assert.equal(paidRow.outstanding_amount,50);
console.log('AP aging vendor credit: explicit same-vendor posted application reduces only linked local open amount');

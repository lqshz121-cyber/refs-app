// A fresh clone must be able to run the gates.
//
// `node_modules` was committed as mode 120000 (a symlink to an absolute POSIX path).
// `.gitignore` said `node_modules/`, and a trailing slash only matches a directory, so
// the symlink slipped straight past it. On a Windows checkout git cannot create a
// symlink, so it writes the target path into a small regular file that points at
// itself. Result: every esbuild-backed gate on a fresh clone dies with
// "Cannot find package 'esbuild'", and `git checkout` inside a worktree destroys an
// installed dependency tree.
//
// This gate keeps dependency directories, build output and absolute-path symlinks out
// of the index.

import { execFileSync } from 'node:child_process';
import { statSync } from 'node:fs';

const failures = [];

function git(args) {
  return execFileSync('git', args, { encoding: 'utf8' });
}

// `ls-files -s` prints: <mode> <object> <stage>\t<path>
const entries = git(['ls-files', '-s'])
  .split('\n')
  .filter(Boolean)
  .map(line => {
    const [meta, path] = line.split('\t');
    const [mode] = meta.split(' ');
    return { mode, path };
  });

const NEVER_TRACK = [
  { re: /(^|\/)node_modules(\/|$)/, why: 'dependency tree — must be installed, never committed' },
  { re: /(^|\/)dist(\/|$)/, why: 'build output — regenerated by `npm run build`' },
  { re: /(^|\/)\.env$/, why: 'may carry secrets' },
];

for (const { mode, path } of entries) {
  for (const rule of NEVER_TRACK) {
    if (rule.re.test(path)) {
      failures.push(
        `tracked path "${path}" (mode ${mode}) must not be in the index: ${rule.why}.\n` +
        `    Fix: git rm --cached -r "${path}" && ensure .gitignore covers it, then commit.`
      );
    }
  }

  // A committed symlink whose target is an absolute path can only ever resolve on the
  // one machine that created it, and cannot be materialised on Windows at all.
  if (mode === '120000') {
    let target = '';
    try {
      target = git(['cat-file', '-p', `:${path}`]).trim();
    } catch {
      target = '';
    }
    if (target.startsWith('/') || /^[A-Za-z]:[\\/]/.test(target)) {
      failures.push(
        `tracked symlink "${path}" points at the absolute path "${target}".\n` +
        `    It resolves on exactly one machine and cannot be created on a Windows checkout.\n` +
        `    Fix: git rm --cached "${path}" and let each environment provide it locally.`
      );
    }
  }
}

// `.gitignore` must carry the slashless form, or the next symlink walks the same path.
const ignore = git(['show', 'HEAD:.gitignore']).split('\n').map(l => l.trim());
if (!ignore.includes('node_modules')) {
  failures.push(
    '.gitignore does not contain a bare `node_modules` line.\n' +
    '    `node_modules/` with a trailing slash matches only a directory, which is exactly\n' +
    '    how a node_modules symlink was committed before. Keep both forms.'
  );
}

if (failures.length) {
  console.error('no-tracked-node-modules FAILED:\n');
  for (const f of failures) console.error('  - ' + f + '\n');
  process.exit(1);
}

// Report, without failing, whether dependencies are actually usable here.
let installed = false;
try {
  installed = statSync('node_modules/esbuild').isDirectory();
} catch {
  installed = false;
}

console.log(
  `no-tracked-node-modules: index is clean of dependency trees, build output and ` +
  `absolute-path symlinks; .gitignore covers both forms` +
  (installed ? '' : ' (note: esbuild is not installed in this working tree — run `npm install`)')
);
